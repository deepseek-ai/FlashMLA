"""Generate explicit template instantiations and print setup.py source entries.

Run from the repository root:
    python3 scripts/generate_instantiations.py

The script creates one .asc file per configuration under INSTANTIATION_DIR and prints its
relative path for inclusion in setup.py. Unchanged files keep their modification timestamps.
"""

from pathlib import Path
from typing import List

INSTANTIATION_DIR = "csrc/ascend_kernels/prefill/sparse/instantiations"

# (format_name, mode, mode_name, extra_model_type)
CONFIGURATIONS = (
    ("v41", "Prefill", "prefill", "V41"),
    ("v41", "Decode", "decode", "V41"),
    ("v41fp4", "Decode", "decode", "V41_FP4"),
)

H_Q_LIST = (64, 128)    # the Ascend kernels support head splits of at most 64 heads per AI core
INDEX_BLOCK_SIZE = 640


def _write_instantiation(path: Path, *, mode: str, h_q: int, have_attn_sink: bool,
                         extra_model_type: str, have_q_o_rope_and_o_cast: bool, have_q_norm: bool) -> None:
    content = (
        "// Generated by scripts/generate_instantiations.py.\n"
        '#include "../kernel.h"\n'
        '#include "../kernel_body.h"\n\n'
        "namespace ascend::prefill::sparse_fwd {\n\n"
        "template void run_sparse_fwd_kernel<Config{"
        f"SparseAttnFwdMode::{mode}, {h_q}, {INDEX_BLOCK_SIZE}, {str(have_attn_sink).lower()}, "
        f"ModelType::V41, ModelType::{extra_model_type}, "
        f"{str(have_q_o_rope_and_o_cast).lower()}, {str(have_q_norm).lower()}"
        f"}}>(const ParamT<SparseAttnFwdMode::{mode}, {str(have_q_o_rope_and_o_cast).lower()}>& params);\n\n"
        "}\n"
    )
    if not path.exists() or path.read_text() != content:
        path.write_text(content)


def generate_instantiations() -> List[str]:
    repo_root = Path(__file__).resolve().parents[1]
    output_dir = repo_root / INSTANTIATION_DIR
    output_dir.mkdir(parents=True, exist_ok=True)
    source_files = []
    for h_q in H_Q_LIST:
        for format_name, mode, mode_name, extra_model_type in CONFIGURATIONS:
            for have_attn_sink in (False, True):
                sink_name = "sink" if have_attn_sink else "nosink"
                # Plain sparse forward / decoding kernel
                path = output_dir / f"{format_name}_h{h_q}_{mode_name}_{sink_name}.asc"
                _write_instantiation(
                    path, mode=mode, h_q=h_q, have_attn_sink=have_attn_sink,
                    extra_model_type=extra_model_type,
                    have_q_o_rope_and_o_cast=False, have_q_norm=False,
                )
                source_files.append(path.relative_to(repo_root).as_posix())
                # Fused norm + RoPE + core attention + RoPE + cast kernel (same template, another specialization)
                for have_q_norm in (False, True):
                    norm_name = "norm" if have_q_norm else "nonorm"
                    path = output_dir / f"{format_name}_h{h_q}_{mode_name}_{sink_name}_{norm_name}.asc"
                    _write_instantiation(
                        path, mode=mode, h_q=h_q, have_attn_sink=have_attn_sink,
                        extra_model_type=extra_model_type,
                        have_q_o_rope_and_o_cast=True, have_q_norm=have_q_norm,
                    )
                    source_files.append(path.relative_to(repo_root).as_posix())
    return source_files


def main() -> None:
    for path in generate_instantiations():
        print(f'"{path}",')


if __name__ == "__main__":
    main()
